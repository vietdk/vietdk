        <h4 class="font-semibold text-gray-900 dark:text-gray-100">DOCX Format:</h4>
        <ul class="list-disc list-inside ml-2 mt-1">
            <li>First heading or paragraph becomes the article title</li>
            <li>Remaining content becomes the article body</li>
            <li>Optional: Add "Category: [name]" on a new line to assign category</li>
        </ul>
    </div>

    <div>
        <h4 class="font-semibold text-gray-900 dark:text-gray-100">XLSX Format:</h4>
        <ul class="list-disc list-inside ml-2 mt-1">
            <li>First row should be column headers</li>
            <li>Required columns: Title, Body/Content</li>
            <li>Optional columns: Category, Date</li>
            <li>Each row creates one article draft</li>
        </ul>
    </div>

    <div class="mt-4 p-3 bg-blue-50 dark:bg-blue-900/20 rounded-lg">
